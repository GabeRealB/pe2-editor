/// The extension's registration: its entry point run, what it registered numbered, and the contract's description of
/// it.
fn registration() -> Result<(Registered, g::Registration), String> {
    let (numbered, out) = register(true)?;
    Ok((numbered, out.unwrap_or_else(|| unreachable!("described"))))
}

/// Run the extension's entry point and number what it registered, the callbacks the host calls back by; `describe`:
/// also describe it as the contract does, which only the host's first instance is asked for - an instance made for a
/// job numbers alone.
fn register(describe: bool) -> Result<(Registered, Option<g::Registration>), String> {
    let extension = __pe2_extension();
    let stored = parse_value(&host::settings()).and_then(|v| v.as_table().cloned()).unwrap_or_default();
    let mut registry = Registry::with_settings(extension.id, stored);
    (extension.register)(&mut registry).map_err(|e| format!("{e:#}"))?;
    let parts = registry.into_parts();
    let mut numbered = Registered {
        fields: vec![],
        views: vec![],
        tools: vec![],
        services: vec![],
        types: vec![],
        ops: vec![],
        reclaimable: None,
    };
    if !describe {
        return Ok((number(parts), None));
    }
    let mut out = g::Registration {
        events: parts.events.clone(),
        hooks: parts
            .hooks
            .iter()
            .map(|h| g::Hook { event: h.event.clone(), op: h.op.clone(), signals: h.signals.clone() })
            .collect(),
        panels: vec![],
        tools: vec![],
        services: vec![],
        ops: vec![],
        types: vec![],
        viewers: vec![],
        commands: parts.commands.iter().map(|c| (c.label.clone(), c.tool.local().to_string())).collect(),
        templates: parts
            .templates
            .iter()
            .map(|t| g::Template {
                name: t.name.clone(),
                label: t.label.clone(),
                node_type: t.node_type.clone(),
                files: t.files.clone(),
                stack: t.stack.clone(),
            })
            .collect(),
        memory: parts.memory.iter().map(|(name, bytes)| (name.to_string(), *bytes)).collect(),
        settings: parts.settings.iter().map(|(s, _)| setting(s)).collect(),
    };
    for (handle, ty) in parts.types.iter().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of types")]
        out.types.push(describe_type(handle as u32, ty, &mut numbered));
    }
    for panel in parts.panels {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of views")]
        let handle = numbered.views.len() as u32;
        out.panels.push(g::Panel {
            handle,
            name: panel.name.local().to_string(),
            label: panel.label.clone(),
            icon: panel.icon.map(icon),
        });
        numbered.views.push(Maker::Panel(panel));
    }
    // Numbered after the panels, as `number` numbers them.
    out.viewers = parts
        .viewers
        .iter()
        .filter_map(|(ty, view)| Some((ty.clone(), views(std::slice::from_ref(view), &mut numbered).pop()?)))
        .collect();
    numbered.tools = calls(parts.tools, &mut out.tools);
    numbered.services = calls(parts.services, &mut out.services);
    imports(&parts.ops, &mut out, &mut numbered);
    numbered.types = parts.types;
    numbered.ops = parts.ops;
    numbered.reclaimable = parts.reclaimable;
    Ok((numbered, Some(out)))
}

/// A type as the contract describes it, its fields and views numbered.
fn describe_type(handle: u32, ty: &TypeDef, numbered: &mut Registered) -> g::ValueType {
    let lists = [&ty.views[..], &ty.inspector, &ty.editors, &ty.contents_views];
    let [own_views, inspector, editors, contents_views] = views_in_order(lists, numbered);
    let signatures = ty
        .signatures
        .iter()
        .map(|s| match s {
            #[expect(clippy::cast_possible_truncation, reason = "an offset in a file's first bytes")]
            Signature::Bytes { offset, bytes } => g::Signature::Bytes((*offset as u32, bytes.clone())),
            Signature::Name(name) => g::Signature::Name(name.clone()),
            Signature::Text => g::Signature::Text,
        })
        .collect();
    g::ValueType {
        handle,
        name: if ty.extends { ty.name.to_string() } else { ty.name.local().to_string() },
        label: ty.label.clone(),
        media_type: ty.media_type.clone(),
        signatures,
        sniff: ty.sniff.is_some(),
        extends: ty.extends,
        data: ty.data,
        values: ty.values.clone(),
        alias: ty.alias.clone(),
        icon: ty.icon.map(|(i, t)| (icon(i), tint(t))),
        fields: ty.fields.iter().map(|f| field(f, numbered)).collect(),
        contents: ty.contents.is_some(),
        part_sheet: ty.part_sheet.is_some(),
        views: own_views,
        inspector,
        editors,
        contents_views,
        stack: ty.stack.clone(),
        takes: ty.takes.clone(),
        extracted: ty.extracted,
    }
}

fn describe_provides(provides: &crate::Provides) -> g::Provides {
    let retain = match provides.retain {
        crate::Retain::Cache => g::Retain::Cache,
        crate::Retain::Build => g::Retain::Build,
        crate::Retain::Transient => g::Retain::Transient,
    };
    let exporter =
        provides.export.as_ref().map(|e| g::Exporter { label: e.label.clone(), extension: e.extension.clone() });
    g::Provides { name: provides.name.clone(), retain, exporter }
}

/// What an extension registered, numbered as describing it numbers it - types' fields and views, panels,
/// operations' fields - without the description.
fn number(parts: crate::registry::Parts) -> Registered {
    let mut numbered = Registered {
        fields: vec![],
        views: vec![],
        tools: vec![],
        services: vec![],
        types: vec![],
        ops: vec![],
        reclaimable: None,
    };
    for ty in &parts.types {
        numbered.fields.extend(ty.fields.iter().cloned());
        views_in_order([&ty.views, &ty.inspector, &ty.editors, &ty.contents_views], &mut numbered);
    }
    numbered.views.extend(parts.panels.into_iter().map(Maker::Panel));
    numbered.views.extend(parts.viewers.into_iter().map(|(_, view)| Maker::Asset(view)));
    for op in &parts.ops {
        numbered.fields.extend(op.fields.iter().cloned());
    }
    numbered.tools = parts.tools;
    numbered.services = parts.services;
    numbered.types = parts.types;
    numbered.ops = parts.ops;
    numbered.reclaimable = parts.reclaimable;
    numbered
}

/// Tools or services, as the contract describes them, numbered in their order.
fn calls(defs: Vec<ToolDef>, out: &mut Vec<g::Tool>) -> Vec<ToolDef> {
    for (handle, def) in defs.iter().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of tools")]
        let handle = handle as u32;
        out.push(g::Tool {
            handle,
            name: def.name.local().to_string(),
            description: def.description.clone(),
            schema: def.schema.clone(),
        });
    }
    defs
}

/// The types and operations registered, as the contract describes them.
fn imports(ops: &[OpDef], out: &mut g::Registration, numbered: &mut Registered) {
    for (handle, op) in ops.iter().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of operations")]
        let handle = handle as u32;
        out.ops.push(g::Op {
            handle,
            name: op.name.local().to_string(),
            label: op.label.clone(),
            inputs: op
                .inputs
                .iter()
                .map(|p| g::Port { name: p.name.clone(), ty: p.ty.to_string(), many: p.many })
                .collect(),
            output: op.output.to_string(),
            fields: op.fields.iter().map(|f| field(f, numbered)).collect(),
            derives: op.derives.clone(),
            inverse: op.inverse.clone(),
            parameter: op.parameter.clone(),
            priority: op.priority,
            provides: op.provides.as_ref().map(describe_provides),
            members: op.members.is_some(),
            also: op.also.iter().map(|(name, ty)| (name.clone(), ty.to_string())).collect(),
            prepares: op.prepare.is_some(),
            stepped: op.stepped,
        });
    }
}

/// What an operation said before it runs, as the contract carries it.
fn prepared_to_wit(prepared: crate::Prepared) -> g::Prepared {
    let input = |from: crate::MicroInput| g::MicroInput { micro: from.micro, port: from.port, files: from.files };
    let micro = |micro: crate::Micro| g::Micro {
        op: micro.op,
        label: micro.label,
        settings: toml::to_string(&micro.settings).unwrap_or_default(),
        ports: micro.ports.into_iter().map(|port| port.into_iter().map(input).collect()).collect(),
        keep: micro.keep,
    };
    g::Prepared {
        needs: prepared.needs.into_iter().map(|need| g::Need { node: need.node, address: need.address }).collect(),
        micros: prepared.micros.into_iter().map(micro).collect(),
    }
}

/// What an operation is lent of its node: the asset the host lent, its files the contents its values hold, by hash.
struct NodeHost<'a>(&'a Lent<'a>);

impl CallHost for NodeHost<'_> {
    fn path(&self) -> &str {
        &self.0.path
    }

    fn node_type(&self) -> Option<&str> {
        self.0.node_type.as_deref()
    }

    fn read(&self, content: &Content) -> crate::Result<Vec<u8>> {
        match content {
            Content::Inline(bytes) => Ok(bytes.clone()),
            Content::Stored { sha1, .. } => Source::read(self.0, sha1),
        }
    }

    fn read_range(&self, content: &Content, offset: u64, len: usize) -> crate::Result<Vec<u8>> {
        match content {
            Content::Inline(bytes) => {
                let start = usize::try_from(offset).unwrap_or(usize::MAX).min(bytes.len());
                Ok(bytes[start..start.saturating_add(len).min(bytes.len())].to_vec())
            }
            Content::Stored { sha1, .. } => Source::read_range(self.0, sha1, offset, len),
        }
    }

    fn writer(&self, name: &str) -> crate::Result<Box<dyn crate::FileWriter>> {
        Source::writer(self.0, name).ok_or_else(|| crate::anyhow!("the host makes no files for this call"))?
    }

    fn entries(&self, folder: &str) -> crate::Result<Vec<String>> {
        Source::entries(self.0, folder).ok_or_else(|| crate::anyhow!("the host lists nothing here"))?
    }

    fn read_entry(&self, path: &str) -> crate::Result<Vec<u8>> {
        Source::read_entry(self.0, path).ok_or_else(|| crate::anyhow!("the host reads nothing here"))?
    }

    fn assets_of(&self, node_type: &str) -> crate::Result<Vec<(String, String)>> {
        Source::assets_of(self.0, node_type).ok_or_else(|| crate::anyhow!("the host finds nothing here"))?
    }

    fn place(&self, path: &str) -> Option<String> {
        Source::place(self.0, path)
    }

    fn node_named(&self, reference: &str) -> Option<crate::NodeNamed> {
        Source::node_named(self.0, reference)
    }

    fn output_of(&self, path: &str, address: &str) -> crate::Result<Data> {
        Source::output_of(self.0, path, address).ok_or_else(|| crate::anyhow!("the host reads nothing here"))?
    }

    fn build_config(&self) -> Option<crate::data::BuildConfig> {
        Source::build_config(self.0)
    }

    fn temp(&self) -> crate::Result<String> {
        Source::temp(self.0).ok_or_else(|| crate::anyhow!("the host has no temporary files for this call"))?
    }

    fn keep(&self, path: &str, name: &str) -> crate::Result<crate::File> {
        Source::keep(self.0, path, name).ok_or_else(|| crate::anyhow!("the host keeps nothing for this call"))?
    }

    fn path_of(&self, content: &Content) -> Option<String> {
        match content {
            Content::Inline(_) => None,
            Content::Stored { sha1, .. } => Source::path_of(self.0, sha1),
        }
    }
}

/// A value as the contract carries it: a list's items that are lists themselves are dropped (it carries one level).
fn to_wit(value: Data) -> types::Value {
    match value {
        Data::List(items) => types::Value::Items(items.into_iter().filter_map(item_to_wit).collect()),
        Data::Image(image) => types::Value::Image(to_image(image)),
        Data::Table(table) => types::Value::Table(toml::to_string(&table).unwrap_or_default()),
        Data::Pcm(pcm) => {
            types::Value::Pcm(types::Pcm { rate: pcm.rate, channels: pcm.channels, samples: pcm.samples })
        }
        Data::Typed(t) => types::Value::Typed(typed_to_wit(t)),
        Data::Video(frame) => types::Value::Video(media::VideoFrame {
            buffer: frame.buffer.into_host(),
            format: pixel_format_to_wit(frame.format),
            width: frame.width,
            height: frame.height,
            timestamp: frame.timestamp,
        }),
        Data::Audio(sound) => types::Value::Audio(media::AudioData {
            buffer: sound.buffer.into_host(),
            format: sample_format_to_wit(sound.format),
            sample_rate: sound.sample_rate,
            channels: sound.channels,
            timestamp: sound.timestamp,
        }),
        Data::Marks(marks) => types::Value::Marks(types::Marks {
            boxes: marks.boxes.into_iter().map(|m| types::Mark { name: m.name, rect: rect(&m.rect) }).collect(),
            summary: marks.summary,
            toggle: marks.toggle,
            legend: marks.legend,
        }),
        // A stream is read, not handed back: an operation's result is what it made of it.
        Data::Stream(_) => types::Value::Items(vec![]),
    }
}

fn pixel_format_to_wit(format: crate::media::PixelFormat) -> media::PixelFormat {
    match format {
        crate::media::PixelFormat::Rgba8888 => media::PixelFormat::Rgba8888,
        crate::media::PixelFormat::Bgra8888 => media::PixelFormat::Bgra8888,
        crate::media::PixelFormat::Yuv420p => media::PixelFormat::Yuv420p,
        crate::media::PixelFormat::Nv12 => media::PixelFormat::Nv12,
    }
}

