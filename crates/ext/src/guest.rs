/// The asset resource behind a lent asset: one the host passed, or one a query returned.
enum Held<'a> {
    Borrowed(&'a host::Asset),
    Owned(host::Asset),
}

/// An asset the host lent, read through its resource: its path and declaration once, its fields parsed when first
/// asked for.
struct Lent<'a> {
    handle: Held<'a>,
    path: String,
    uid: Option<String>,
    kind: Option<String>,
    role: Option<String>,
    declaration: String,
    fields: OnceCell<Table>,
}

impl<'a> Lent<'a> {
    fn new(handle: Held<'a>) -> Lent<'a> {
        let resource = match &handle {
            Held::Borrowed(asset) => *asset,
            Held::Owned(asset) => asset,
        };
        let (path, uid, kind, role) = (resource.path(), resource.uid(), resource.kind(), resource.role());
        let declaration = resource.declaration();
        Lent { handle, path, uid, kind, role, declaration, fields: OnceCell::new() }
    }

    fn borrowed(asset: &'a host::Asset) -> Lent<'a> {
        Lent::new(Held::Borrowed(asset))
    }

    fn resource(&self) -> &host::Asset {
        match &self.handle {
            Held::Borrowed(asset) => asset,
            Held::Owned(asset) => asset,
        }
    }

    fn asset(&self) -> Asset<'_> {
        Asset::new(self, self.kind.as_deref(), self.role.as_deref())
    }
}

impl Source for Lent<'_> {
    fn path(&self) -> &str {
        &self.path
    }

    fn uid(&self) -> Option<&str> {
        self.uid.as_deref()
    }

    fn fields(&self) -> &Table {
        self.fields.get_or_init(|| toml::from_str(&self.declaration).unwrap_or_default())
    }

    fn declaration(&self) -> &str {
        &self.declaration
    }

    fn has_file(&self, name: &str) -> bool {
        self.resource().has_file(name)
    }

    fn read(&self, name: &str) -> crate::Result<Vec<u8>> {
        self.resource().read(name).map_err(crate::Error::msg)
    }

    fn size(&self, name: &str) -> Option<u64> {
        self.resource().size(name)
    }

    fn read_range(&self, name: &str, offset: u64, len: usize) -> crate::Result<Vec<u8>> {
        let len = u32::try_from(len).unwrap_or(u32::MAX);
        self.resource().read_range(name, offset, len).map_err(crate::Error::msg)
    }

    fn writer(&self, name: &str) -> Option<crate::Result<Box<dyn crate::FileWriter>>> {
        let writer = self.resource().writer(name).map_err(crate::Error::msg);
        Some(writer.map(|w| Box::new(HostWriter(Some(w))) as Box<dyn crate::FileWriter>))
    }
}

/// A file being made through the host's writer: appended to there, finished into the file the host made.
struct HostWriter(Option<host::Writer>);

// SAFETY: a component runs on one thread.
unsafe impl Send for HostWriter {}

impl crate::FileWriter for HostWriter {
    fn append(&mut self, bytes: &[u8]) -> crate::Result<()> {
        let writer = self.0.as_ref().ok_or_else(|| crate::anyhow!("finished"))?;
        writer.append(bytes).map_err(crate::Error::msg)
    }

    fn finish(mut self: Box<Self>) -> crate::Result<crate::File> {
        let writer = self.0.take().ok_or_else(|| crate::anyhow!("finished"))?;
        writer.finish().map(file_from_wit).map_err(crate::Error::msg)
    }
}

/// The project the host lent, its answers kept for the call: an asset a query returns lives as long as the project.
struct Lens<'a> {
    project: &'a host::Project,
    #[expect(clippy::vec_box, reason = "a found asset stays where it is while more are found: assets borrow it")]
    found: RefCell<Vec<Box<Lent<'static>>>>,
}

impl<'a> Lens<'a> {
    fn new(project: &'a host::Project) -> Lens<'a> {
        Lens { project, found: RefCell::new(vec![]) }
    }

    fn keep(&self, asset: host::Asset) -> Asset<'_> {
        let lent = Box::new(Lent::new(Held::Owned(asset)));
        let at: *const Lent<'static> = &raw const *lent;
        self.found.borrow_mut().push(lent);
        // SAFETY: the box is kept, unmoved and unchanged, until the lens goes, and the asset borrows the lens.
        unsafe { &*at }.asset()
    }
}

impl Project for Lens<'_> {
    fn asset(&self, path: &str) -> Option<Asset<'_>> {
        self.project.asset(path).map(|a| self.keep(a))
    }

    fn resolve(&self, reference: &Value) -> Option<Asset<'_>> {
        self.project.resolve(&value_text(reference)).map(|a| self.keep(a))
    }

    fn find(&self, kind: &str) -> Vec<Asset<'_>> {
        self.project.find(kind).into_iter().map(|a| self.keep(a)).collect()
    }

    fn selection(&self) -> Option<Asset<'_>> {
        self.project.selection().map(|a| self.keep(a))
    }

    fn look(&self, path: &str) -> usize {
        self.project.look(path) as usize
    }

    fn picture(&self, path: &str, look: usize) -> Option<crate::Result<Image>> {
        let look = u32::try_from(look).unwrap_or(u32::MAX);
        self.project.picture(path, look).map(|made| made.map(from_image).map_err(crate::Error::msg))
    }

    fn part(&self, path: &str, part: &str) -> Option<crate::Result<Image>> {
        self.project.part(path, part).map(|made| made.map(from_image).map_err(crate::Error::msg))
    }

    fn parts(&self, path: &str) -> Vec<crate::Part> {
        self.project.parts(path).into_iter().map(|(id, label, made_of)| crate::Part { id, label, made_of }).collect()
    }

    fn call(&self, service: &str, arguments: &Value) -> crate::Result<Value> {
        let answer = self.project.call(service, &value_text(arguments)).map_err(crate::Error::msg)?;
        parse_value(&answer).ok_or_else(|| crate::anyhow!("{service}: its answer is not TOML"))
    }
}

fn from_image(image: types::Image) -> Image {
    Image { width: image.width as usize, height: image.height as usize, rgba: image.rgba }
}

/// A frame's `ui`: the one lent, or a row, a section or a body of it.
enum Handle<'a> {
    Lent(&'a host::Ui),
    Child(host::Ui),
}

struct Frame<'a> {
    ui: Handle<'a>,
    project: &'a Lens<'a>,
    asset: Option<Asset<'a>>,
    look: usize,
}

impl Frame<'_> {
    fn ui(&self) -> &host::Ui {
        match &self.ui {
            Handle::Lent(ui) => ui,
            Handle::Child(ui) => ui,
        }
    }

    fn child(&self, ui: host::Ui) -> Box<dyn UiHost + '_> {
        Box::new(Frame { ui: Handle::Child(ui), project: self.project, asset: self.asset, look: self.look })
    }
}

fn style(style: Style) -> types::Style {
    match style {
        Style::Normal => types::Style::Normal,
        Style::Weak => types::Style::Weak,
        Style::Note => types::Style::Note,
        Style::Strong => types::Style::Strong,
        Style::Error => types::Style::Error,
    }
}

impl UiHost for Frame<'_> {
    fn label(&mut self, text: &str, style: Style) {
        self.ui().label(text, self::style(style));
    }

    fn button(&mut self, text: &str) -> bool {
        self.ui().button(text)
    }

    fn icon_button(&mut self, icon: Icon, hint: &str) -> bool {
        self.ui().icon_button(self::icon(icon), hint)
    }

    fn checkbox(&mut self, text: &str, value: &mut bool) -> bool {
        let new = self.ui().checkbox(text, *value);
        let toggled = new != *value;
        *value = new;
        toggled
    }

    fn badge(&mut self, text: &str) {
        self.ui().badge(text);
    }

    fn chip(&mut self, text: &str) -> bool {
        self.ui().chip(text)
    }

    fn image(&mut self, texture: &Texture, width: f32, height: f32) {
        self.ui().image(texture.handle(), width, height);
    }

    fn reference(&mut self, reference: &Value) {
        self.ui().reference(&value_text(reference));
    }

    fn field(&mut self, key: &str, value: &Value) {
        self.ui().field(key, &value_text(value));
    }

    fn tooltip(&mut self, text: &str) {
        self.ui().tooltip(text);
    }

    fn text_edit(&mut self, id: &str, text: &mut String) -> bool {
        let (edited, committed) = self.ui().text_edit(id, text);
        *text = edited;
        committed
    }

    fn combo(&mut self, id: &str, selected: &str, options: &[String]) -> Option<usize> {
        self.ui().combo(id, selected, options).map(|i| i as usize)
    }

    fn editable(&self) -> bool {
        self.ui().editable()
    }

    fn set(&mut self, key: &str, value: Option<&Value>) {
        self.ui().set(key, value.map(value_text).as_deref());
    }

    fn horizontal(&mut self) -> Box<dyn UiHost + '_> {
        let row = self.ui().horizontal();
        self.child(row)
    }

    fn wrapped(&mut self) -> Box<dyn UiHost + '_> {
        let row = self.ui().wrapped();
        self.child(row)
    }

    fn indented(&mut self) -> Box<dyn UiHost + '_> {
        let inner = self.ui().indented();
        self.child(inner)
    }

    fn section(&mut self, title: &str) -> Box<dyn UiHost + '_> {
        let section = self.ui().section(title);
        self.child(section)
    }

    fn collapsing(&mut self, id: &str, title: &str, note: &str) -> Option<Box<dyn UiHost + '_>> {
        let body = self.ui().collapsing(id, title, note)?;
        Some(self.child(body))
    }

    fn table(&mut self, id: &str, rows: &[Vec<crate::Cell>]) -> Option<(usize, usize)> {
        let rows: Vec<Vec<host::Cell>> = rows
            .iter()
            .map(|row| {
                row.iter()
                    .map(|cell| match cell {
                        crate::Cell::Empty => host::Cell::Empty,
                        crate::Cell::Text(text, style) => host::Cell::Text((text.clone(), self::style(*style))),
                        crate::Cell::Reference(value) => host::Cell::Reference(value_text(value)),
                        crate::Cell::Button(i, hint) => host::Cell::Button((icon(*i), hint.clone())),
                    })
                    .collect()
            })
            .collect();
        let (row, column) = self.ui().table(id, &rows)?;
        Some((row as usize, column as usize))
    }

    fn canvas(&mut self, canvas: &Canvas) {
        let placed = |p: &crate::Placed| host::Placed { rect: rect(&p.rect), label: p.label.clone(), link: p.link.clone() };
        self.ui().canvas(&host::Canvas {
            width: canvas.width,
            height: canvas.height,
            pictures: canvas.pictures.iter().map(|p| (p.texture.handle(), placed(p))).collect(),
            boxes: canvas
                .boxes
                .iter()
                .map(|b| host::Marked { name: b.name.clone(), rect: rect(&b.rect), highlight: b.highlight })
                .collect(),
            summary: canvas.summary.clone(),
            toggle: canvas.toggle.clone(),
            legend: canvas.legend,
            grid: canvas.grid,
        });
    }

    fn picture(&mut self, path: &str, look: usize) -> Option<Result<crate::Texture, String>> {
        let look = u32::try_from(look).unwrap_or(u32::MAX);
        let shown = self.ui().picture(path, look)?;
        Some(shown.map(|(handle, width, height)| {
            crate::Texture::from_host(format!("{path}#{look}#picture"), width as usize, height as usize, handle)
        }))
    }

    fn navigate(&mut self, path: &str) {
        self.ui().navigate(path);
    }

    fn asset(&self) -> Option<Asset<'_>> {
        self.asset
    }

    fn look(&self) -> usize {
        self.look
    }

    fn project(&self) -> &dyn Project {
        self.project
    }
}

/// A field as the host is told of it, numbered.
fn field(f: &Field, numbered: &mut Registered) -> g::Field {
    #[expect(clippy::cast_possible_truncation, reason = "a handful of fields")]
    let handle = numbered.fields.len() as u32;
    numbered.fields.push(f.clone());
    g::Field {
        handle,
        key: f.key.clone(),
        label: f.label.clone(),
        format: f.format.is_some(),
        brief: f.brief.is_some(),
        choices: f.choices.iter().map(|(v, label)| (value_text(v), label.clone())).collect(),
        read_only: f.read_only,
        custom: f.custom,
    }
}

/// A setting as the host is told of it.
fn setting(s: &crate::Setting) -> g::Setting {
    g::Setting {
        key: s.key.clone(),
        label: s.label.clone(),
        help: s.help.clone(),
        default: value_text(&s.default),
        scope: match s.scope {
            crate::Scope::Project => g::Scope::Project,
            crate::Scope::User => g::Scope::User,
        },
        choices: s.choices.iter().map(|(v, label)| (value_text(v), label.clone())).collect(),
    }
}

/// Views as the host is told of them, numbered.
fn views(list: &[ViewDef], numbered: &mut Registered) -> Vec<g::View> {
    list.iter()
        .map(|v| {
            #[expect(clippy::cast_possible_truncation, reason = "a handful of views")]
            let handle = numbered.views.len() as u32;
            numbered.views.push(Maker::Asset(v.clone()));
            g::View { handle, name: v.name.clone() }
        })
        .collect()
}

/// The extension, as the component exports it.
pub struct Component;

impl g::Guest for Component {
    type ViewState = ViewState;
    type Extraction = Extraction;
    type Generator = Generating;

    fn start_stream(
        op: u32,
        node: &host::Asset,
        inputs: Vec<Vec<types::Value>>,
        settings: String,
        parameter: Option<String>,
    ) -> Result<g::Generator, String> {
        let def = registered().ops.get(op as usize).ok_or("no such operation")?;
        let start = def.start.as_ref().ok_or("it is no stream")?;
        let lent = Lent::borrowed(node);
        let settings: Table = toml::from_str(&settings).unwrap_or_default();
        let inputs = inputs.into_iter().map(|port| port.into_iter().map(from_wit).collect()).collect();
        let host = NodeHost(&lent);
        let mut call = crate::Call { inputs, settings: &settings, parameter_text: parameter.as_deref(), host: &host };
        let generator = start(&mut call).map_err(|e| format!("{e:#}"))?;
        Ok(g::Generator::new(Generating { generator: RefCell::new(generator), settings, parameter }))
    }

    fn describe() -> g::About {
        let extension = __pe2_extension();
        g::About {
            id: extension.id.to_string(),
            version: extension.version.to_string(),
            requires: extension.requires.iter().map(ToString::to_string).collect(),
        }
    }

    fn register() -> Result<g::Registration, String> {
        let (numbered, out) = registration()?;
        let _ = REGISTERED.set(numbered);
        Ok(out)
    }

    #[expect(clippy::unused_async_trait_impl, reason = "async in the contract, so the host can cancel a long call")]
    async fn run_op(
        op: u32,
        node: &host::Asset,
        inputs: Vec<Vec<types::Value>>,
        settings: String,
        parameter: Option<String>,
    ) -> Result<types::Value, String> {
        let def = registered().ops.get(op as usize).ok_or("no such operation")?;
        let lent = Lent::borrowed(node);
        let settings: Table = toml::from_str(&settings).unwrap_or_default();
        let inputs = inputs.into_iter().map(|port| port.into_iter().map(from_wit).collect()).collect();
        let host = NodeHost(&lent);
        let mut call = crate::Call { inputs, settings: &settings, parameter_text: parameter.as_deref(), host: &host };
        (def.run)(&mut call).map(to_wit).map_err(|e| format!("{e:#}"))
    }

    fn members(kind: u32, output: u32, asset: &host::Asset) -> Vec<(String, String)> {
        let lent = Lent::borrowed(asset);
        let output = registered().kinds.get(kind as usize).and_then(|k| k.outputs.get(output as usize));
        output.and_then(|o| o.members.as_ref()).map_or_else(Vec::new, |members| members(&lent.asset()))
    }

    fn format(field: u32, brief: bool, value: String) -> Option<String> {
        let field = &registered().fields[field as usize];
        let format = if brief { field.brief.as_ref() } else { field.format.as_ref() }?;
        format(&parse_value(&value)?)
    }

    fn parts(kind: u32, asset: &host::Asset) -> Vec<g::Part> {
        let lent = Lent::borrowed(asset);
        let parts = registered().kinds[kind as usize].parts.as_ref();
        parts.map_or_else(Vec::new, |parts| parts(&lent.asset()))
            .into_iter()
            .map(|p| g::Part { id: p.id, label: p.label, made_of: p.made_of })
            .collect()
    }

    fn sniff(ty: u32, name: String, size: u64, head: Vec<u8>) -> Option<String> {
        let sniff = registered().types.get(ty as usize)?.sniff.as_ref()?;
        sniff(&name, size, &head).map(|r| r.version.unwrap_or_default())
    }

    fn reclaimable() -> bool {
        registered().reclaimable.as_ref().is_none_or(|reclaimable| reclaimable())
    }

    #[expect(clippy::unused_async_trait_impl, reason = "async in the contract, so the host can cancel a long call")]
    async fn serve(service: u32, project: &host::Project, arguments: String) -> Result<String, String> {
        let service = registered().services.get(service as usize).ok_or("no such service")?;
        let arguments = parse_value(&arguments).unwrap_or_else(|| Value::Table(Table::new()));
        let lens = Lens::new(project);
        (service.run)(&lens, &arguments).map(|answer| value_text(&answer)).map_err(|e| format!("{e:#}"))
    }

    #[expect(clippy::unused_async_trait_impl, reason = "async in the contract, so the host can cancel a long call")]
    async fn run(tool: u32, project: &host::Project, arguments: String) -> Result<String, String> {
        let tool = registered().tools.get(tool as usize).ok_or("no such tool")?;
        let arguments = parse_value(&arguments).unwrap_or_else(|| Value::Table(Table::new()));
        let lens = Lens::new(project);
        (tool.run)(&lens, &arguments).map(|answer| value_text(&answer)).map_err(|e| format!("{e:#}"))
    }
}

/// The extension's registration: its entry point run, what it registered numbered, and the contract's description of
/// it.
fn registration() -> Result<(Registered, g::Registration), String> {
    let (numbered, out) = register(true)?;
    Ok((numbered, out.unwrap_or_else(|| unreachable!("described"))))
}

/// Run the extension's entry point and number what it registered, the callbacks the host calls back by; `describe`:
/// also describe it as the contract does, which only the host's first instance is asked for - an instance made for a
/// job numbers alone.
fn register(describe: bool) -> Result<(Registered, Option<g::Registration>), String> {
    let extension = __pe2_extension();
    let stored = parse_value(&host::settings()).and_then(|v| v.as_table().cloned()).unwrap_or_default();
    let mut registry = Registry::with_settings(extension.id, stored);
    (extension.register)(&mut registry).map_err(|e| format!("{e:#}"))?;
    let parts = registry.into_parts();
    let mut numbered = Registered {
        kinds: vec![],
        fields: vec![],
        views: vec![],
        tools: vec![],
        services: vec![],
        types: vec![],
        ops: vec![],
        extractors: vec![],
        reclaimable: None,
    };
    if !describe {
        return Ok((number(parts), None));
    }
    let mut out = g::Registration {
        kinds: vec![],
        roles: vec![],
        panels: vec![],
        tools: vec![],
        services: vec![],
        ops: vec![],
        types: vec![],
        extractors: vec![],
        memory: parts.memory.iter().map(|(name, bytes)| (name.to_string(), *bytes)).collect(),
        settings: parts.settings.iter().map(|(s, _)| setting(s)).collect(),
    };
    for kind in &parts.kinds {
        out.kinds.push(describe_kind(kind, &mut numbered));
    }
    for role in &parts.roles {
        out.roles.push(g::Role {
            name: role.name.local().to_string(),
            kind: role.kind.to_string(),
            alias: role.alias.clone(),
            label: role.label.clone(),
            fields: role.fields.iter().map(|f| field(f, &mut numbered)).collect(),
            views: views(&role.views, &mut numbered),
            inspector: views(&role.inspector, &mut numbered),
        });
    }
    for panel in parts.panels {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of views")]
        let handle = numbered.views.len() as u32;
        out.panels.push(g::Panel {
            handle,
            name: panel.name.local().to_string(),
            label: panel.label.clone(),
            icon: panel.icon.map(icon),
        });
        numbered.views.push(Maker::Panel(panel));
    }
    numbered.tools = calls(parts.tools, &mut out.tools);
    numbered.services = calls(parts.services, &mut out.services);
    imports(&parts.types, &parts.ops, &mut out, &mut numbered);
    for (handle, extractor) in parts.extractors.iter().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of extractors")]
        let handle = handle as u32;
        out.extractors.push(g::Extractor {
            handle,
            name: extractor.name.local().to_string(),
            kind: extractor.kind.to_string(),
            roles: extractor.roles.iter().map(ToString::to_string).collect(),
        });
    }
    numbered.types = parts.types;
    numbered.ops = parts.ops;
    numbered.extractors = parts.extractors;
    numbered.kinds = parts.kinds;
    numbered.reclaimable = parts.reclaimable;
    Ok((numbered, Some(out)))
}

/// A kind as the contract describes it, its fields and views numbered.
fn describe_kind(kind: &KindDef, numbered: &mut Registered) -> g::Kind {
    g::Kind {
        name: kind.name.local().to_string(),
        alias: kind.alias.clone(),
        label: kind.label.clone(),
        icon: kind.icon.map(|(i, t)| (icon(i), tint(t))),
        fields: kind.fields.iter().map(|f| field(f, numbered)).collect(),
        parts: kind.parts.is_some(),
        views: views(&kind.views, numbered),
        inspector: views(&kind.inspector, numbered),
        outputs: kind
            .outputs
            .iter()
            .map(|o| g::Output {
                name: o.name.clone(),
                op: o.op.clone(),
                retain: match o.retain {
                    crate::Retain::Cache => g::Retain::Cache,
                    crate::Retain::Build => g::Retain::Build,
                    crate::Retain::Transient => g::Retain::Transient,
                },
                members: o.members.is_some(),
            })
            .collect(),
        stack: kind.stack.clone(),
    }
}

/// What an extension registered, numbered as describing it numbers it - kinds' fields and views, roles', panels,
/// operations' fields - without the description.
fn number(parts: crate::registry::Parts) -> Registered {
    let mut numbered = Registered {
        kinds: vec![],
        fields: vec![],
        views: vec![],
        tools: vec![],
        services: vec![],
        types: vec![],
        ops: vec![],
        extractors: vec![],
        reclaimable: None,
    };
    for kind in &parts.kinds {
        numbered.fields.extend(kind.fields.iter().cloned());
        numbered.views.extend(kind.views.iter().chain(&kind.inspector).cloned().map(Maker::Asset));
    }
    for role in &parts.roles {
        numbered.fields.extend(role.fields.iter().cloned());
        numbered.views.extend(role.views.iter().chain(&role.inspector).cloned().map(Maker::Asset));
    }
    numbered.views.extend(parts.panels.into_iter().map(Maker::Panel));
    for op in &parts.ops {
        numbered.fields.extend(op.fields.iter().cloned());
    }
    numbered.tools = parts.tools;
    numbered.services = parts.services;
    numbered.types = parts.types;
    numbered.ops = parts.ops;
    numbered.extractors = parts.extractors;
    numbered.kinds = parts.kinds;
    numbered.reclaimable = parts.reclaimable;
    numbered
}

/// Tools or services, as the contract describes them, numbered in their order.
fn calls(defs: Vec<ToolDef>, out: &mut Vec<g::Tool>) -> Vec<ToolDef> {
    for (handle, def) in defs.iter().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of tools")]
        let handle = handle as u32;
        out.push(g::Tool {
            handle,
            name: def.name.local().to_string(),
            description: def.description.clone(),
            schema: def.schema.clone(),
        });
    }
    defs
}

/// The types and operations registered, as the contract describes them.
fn imports(types: &[TypeDef], ops: &[OpDef], out: &mut g::Registration, numbered: &mut Registered) {
    for (handle, ty) in types.iter().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of types")]
        let handle = handle as u32;
        let signatures = ty
            .signatures
            .iter()
            .map(|s| match s {
                #[expect(clippy::cast_possible_truncation, reason = "an offset in a file's first bytes")]
                Signature::Bytes { offset, bytes } => g::Signature::Bytes((*offset as u32, bytes.clone())),
                Signature::Name(name) => g::Signature::Name(name.clone()),
                Signature::Text => g::Signature::Text,
            })
            .collect();
        out.types.push(g::ValueType {
            handle,
            name: ty.name.local().to_string(),
            label: ty.label.clone(),
            media_type: ty.media_type.clone(),
            signatures,
            sniff: ty.sniff.is_some(),
        });
    }
    for (handle, op) in ops.iter().enumerate() {
        #[expect(clippy::cast_possible_truncation, reason = "a handful of operations")]
        let handle = handle as u32;
        out.ops.push(g::Op {
            handle,
            name: op.name.local().to_string(),
            label: op.label.clone(),
            inputs: op.inputs.iter().map(|p| g::Port { name: p.name.clone(), ty: p.ty.to_string(), many: p.many }).collect(),
            output: op.output.to_string(),
            fields: op.fields.iter().map(|f| field(f, numbered)).collect(),
            derives: op.derives.clone(),
            inverse: op.inverse.clone(),
            parameter: op.parameter.clone(),
            priority: op.priority,
        });
    }
}

/// What an operation is lent of its node: the asset the host lent, its files the contents its values hold, by hash.
struct NodeHost<'a>(&'a Lent<'a>);

impl CallHost for NodeHost<'_> {
    fn path(&self) -> &str {
        &self.0.path
    }

    fn kind(&self) -> Option<&str> {
        self.0.kind.as_deref()
    }

    fn role(&self) -> Option<&str> {
        self.0.role.as_deref()
    }

    fn fields(&self) -> &Table {
        Source::fields(self.0)
    }

    fn read(&self, content: &Content) -> crate::Result<Vec<u8>> {
        match content {
            Content::Inline(bytes) => Ok(bytes.clone()),
            Content::Stored { sha1, .. } => Source::read(self.0, sha1),
        }
    }

    fn read_range(&self, content: &Content, offset: u64, len: usize) -> crate::Result<Vec<u8>> {
        match content {
            Content::Inline(bytes) => {
                let start = usize::try_from(offset).unwrap_or(usize::MAX).min(bytes.len());
                Ok(bytes[start..start.saturating_add(len).min(bytes.len())].to_vec())
            }
            Content::Stored { sha1, .. } => Source::read_range(self.0, sha1, offset, len),
        }
    }

    fn writer(&self, name: &str) -> crate::Result<Box<dyn crate::FileWriter>> {
        Source::writer(self.0, name).ok_or_else(|| crate::anyhow!("the host makes no files for this call"))?
    }
}

/// A value as the contract carries it: a list's items that are lists themselves are dropped (it carries one level).
fn to_wit(value: Data) -> types::Value {
    match value {
        Data::List(items) => types::Value::Items(items.into_iter().filter_map(item_to_wit).collect()),
        Data::Image(image) => types::Value::Image(to_image(image)),
        Data::Table(table) => types::Value::Table(toml::to_string(&table).unwrap_or_default()),
        Data::Pcm(pcm) => types::Value::Pcm(types::Pcm { rate: pcm.rate, channels: pcm.channels, samples: pcm.samples }),
        Data::Typed(t) => types::Value::Typed(typed_to_wit(t)),
        Data::Video(frame) => types::Value::Video(media::VideoFrame {
            buffer: frame.buffer.into_host(),
            format: pixel_format_to_wit(frame.format),
            width: frame.width,
            height: frame.height,
            timestamp: frame.timestamp,
        }),
        Data::Audio(sound) => types::Value::Audio(media::AudioData {
            buffer: sound.buffer.into_host(),
            format: sample_format_to_wit(sound.format),
            sample_rate: sound.sample_rate,
            channels: sound.channels,
            timestamp: sound.timestamp,
        }),
    }
}

fn pixel_format_to_wit(format: crate::media::PixelFormat) -> media::PixelFormat {
    match format {
        crate::media::PixelFormat::Rgba8888 => media::PixelFormat::Rgba8888,
        crate::media::PixelFormat::Bgra8888 => media::PixelFormat::Bgra8888,
        crate::media::PixelFormat::Yuv420p => media::PixelFormat::Yuv420p,
        crate::media::PixelFormat::Nv12 => media::PixelFormat::Nv12,
    }
}

fn pixel_format_from_wit(format: media::PixelFormat) -> crate::media::PixelFormat {
    match format {
        media::PixelFormat::Rgba8888 => crate::media::PixelFormat::Rgba8888,
        media::PixelFormat::Bgra8888 => crate::media::PixelFormat::Bgra8888,
        media::PixelFormat::Yuv420p => crate::media::PixelFormat::Yuv420p,
        media::PixelFormat::Nv12 => crate::media::PixelFormat::Nv12,
    }
}

fn sample_format_to_wit(format: crate::media::SampleFormat) -> media::SampleFormat {
    match format {
        crate::media::SampleFormat::S16Interleaved => media::SampleFormat::S16Interleaved,
        crate::media::SampleFormat::F32Planar => media::SampleFormat::F32Planar,
    }
}

fn sample_format_from_wit(format: media::SampleFormat) -> crate::media::SampleFormat {
    match format {
        media::SampleFormat::S16Interleaved => crate::media::SampleFormat::S16Interleaved,
        media::SampleFormat::F32Planar => crate::media::SampleFormat::F32Planar,
    }
}

/// The frame layouts the host takes.
pub(crate) fn pixel_formats() -> Vec<crate::media::PixelFormat> {
    media::pixel_formats().into_iter().map(pixel_format_from_wit).collect()
}

/// The sound layouts the host takes.
pub(crate) fn sample_formats() -> Vec<crate::media::SampleFormat> {
    media::sample_formats().into_iter().map(sample_format_from_wit).collect()
}

fn item_to_wit(value: Data) -> Option<types::Item> {
    Some(match to_wit(value) {
        types::Value::Image(i) => types::Item::Image(i),
        types::Value::Table(t) => types::Item::Table(t),
        types::Value::Pcm(p) => types::Item::Pcm(p),
        types::Value::Typed(t) => types::Item::Typed(t),
        types::Value::Video(v) => types::Item::Video(v),
        types::Value::Audio(a) => types::Item::Audio(a),
        types::Value::Items(_) => return None,
    })
}

fn file_to_wit(f: crate::File) -> types::File {
    let content = match f.content {
        Content::Inline(bytes) => types::Content::Inline(bytes),
        Content::Stored { sha1, size } => types::Content::Stored((sha1, size)),
    };
    types::File { name: f.name, content }
}

fn typed_to_wit(t: crate::Typed) -> types::Typed {
    types::Typed {
        ty: t.ty,
        also: t.also,
        files: t.files.into_iter().map(file_to_wit).collect(),
        settings: toml::to_string(&t.settings).unwrap_or_default(),
        notes: t.notes,
    }
}

/// A value as the contract carried it.
fn from_wit(value: types::Value) -> Data {
    match value {
        types::Value::Image(i) => item_from_wit(types::Item::Image(i)),
        types::Value::Table(t) => item_from_wit(types::Item::Table(t)),
        types::Value::Pcm(p) => item_from_wit(types::Item::Pcm(p)),
        types::Value::Typed(t) => item_from_wit(types::Item::Typed(t)),
        types::Value::Video(v) => item_from_wit(types::Item::Video(v)),
        types::Value::Audio(a) => item_from_wit(types::Item::Audio(a)),
        types::Value::Items(items) => Data::List(items.into_iter().map(item_from_wit).collect()),
    }
}

fn item_from_wit(item: types::Item) -> Data {
    match item {
        types::Item::Image(i) => Data::Image(Image { width: i.width as usize, height: i.height as usize, rgba: i.rgba }),
        types::Item::Table(t) => Data::Table(toml::from_str(&t).unwrap_or_default()),
        types::Item::Pcm(p) => Data::Pcm(crate::Pcm { rate: p.rate, channels: p.channels, samples: p.samples }),
        types::Item::Typed(t) => Data::Typed(crate::Typed {
            ty: t.ty,
            also: t.also,
            files: t.files.into_iter().map(file_from_wit).collect(),
            settings: toml::from_str(&t.settings).unwrap_or_default(),
            notes: t.notes,
        }),
        types::Item::Video(v) => Data::Video(crate::media::VideoFrame {
            buffer: crate::media::MediaBuffer::from_host(v.buffer),
            format: pixel_format_from_wit(v.format),
            width: v.width,
            height: v.height,
            timestamp: v.timestamp,
        }),
        types::Item::Audio(a) => Data::Audio(crate::media::AudioData {
            buffer: crate::media::MediaBuffer::from_host(a.buffer),
            format: sample_format_from_wit(a.format),
            sample_rate: a.sample_rate,
            channels: a.channels,
            timestamp: a.timestamp,
        }),
    }
}

fn file_from_wit(f: types::File) -> crate::File {
    let content = match f.content {
        types::Content::Inline(bytes) => Content::Inline(bytes),
        types::Content::Stored((sha1, size)) => Content::Stored { sha1, size },
    };
    crate::File { name: f.name, content }
}

/// A view, kept between frames.
pub struct ViewState(RefCell<Box<dyn View>>);

impl g::GuestViewState for ViewState {
    fn new(view: u32, asset: Option<&host::Asset>) -> ViewState {
        let made = match (&registered().views[view as usize], asset) {
            (Maker::Asset(view), Some(asset)) => (view.make)(&Lent::borrowed(asset).asset()),
            (Maker::Panel(panel), _) => (panel.make)(),
            (Maker::Asset(_), None) => Box::new(Missing),
        };
        ViewState(RefCell::new(made))
    }

    fn show(&self, ui: &host::Ui, project: &host::Project, asset: Option<&host::Asset>, look: u32) {
        let shown = asset.map(Lent::borrowed);
        let lens = Lens::new(project);
        let asset = shown.as_ref().map(Lent::asset);
        let mut frame = Frame { ui: Handle::Lent(ui), project: &lens, asset, look: look as usize };
        self.0.borrow_mut().show(&mut crate::Ui::new(&mut frame));
    }
}

/// A stream's generator, kept while its stream is read, with the settings and parameter it was started with.
pub struct Generating {
    generator: RefCell<Box<dyn crate::Generator>>,
    settings: Table,
    parameter: Option<String>,
}

impl Generating {
    /// Call the generator with its node lent.
    fn with<R>(&self, node: &host::Asset, call: impl FnOnce(&mut dyn crate::Generator, &crate::Call<'_>) -> crate::Result<R>) -> Result<R, String> {
        let lent = Lent::borrowed(node);
        let host = NodeHost(&lent);
        let lent_call = crate::Call { inputs: vec![], settings: &self.settings, parameter_text: self.parameter.as_deref(), host: &host };
        call(&mut **self.generator.borrow_mut(), &lent_call).map_err(|e| format!("{e:#}"))
    }
}

impl g::GuestGenerator for Generating {
    fn header(&self) -> String {
        toml::to_string(&self.generator.borrow().header()).unwrap_or_default()
    }

    fn next(&self, node: &host::Asset, count: u32) -> Result<Vec<types::Value>, String> {
        let items = self.with(node, |generator, call| generator.next(call, count as usize))?;
        Ok(items.into_iter().map(to_wit).collect())
    }

    fn seek(&self, node: &host::Asset, position: u64) -> Result<bool, String> {
        self.with(node, |generator, call| generator.seek(call, position))
    }
}

/// An extraction session, kept between assets.
pub struct Extraction(RefCell<Box<dyn crate::Extraction>>);

/// The host's declarations, as an extractor reads them.
struct Declarations<'a>(&'a host::Declarations);

impl crate::Declared for Declarations<'_> {
    fn declarations(&self, kind: &str) -> Vec<(String, Table)> {
        self.0.of_kind(kind).into_iter().filter_map(|(path, text)| Some((path, toml::from_str(&text).ok()?))).collect()
    }
}

/// The host's discs, as an extractor reads them.
struct Discs<'a>(&'a host::Discs);

impl crate::Discs for Discs<'_> {
    fn read(&mut self, at: &Table) -> crate::Result<Vec<u8>> {
        let at = toml::to_string(at)?;
        self.0.read(&at).map_err(|e| crate::anyhow!(e))
    }

    fn size(&mut self, at: &Table) -> crate::Result<u64> {
        let at = toml::to_string(at)?;
        self.0.size(&at).map_err(|e| crate::anyhow!(e))
    }

    fn read_range(&mut self, at: &Table, offset: u64, len: usize) -> crate::Result<Vec<u8>> {
        let at = toml::to_string(at)?;
        let len = u32::try_from(len).unwrap_or(u32::MAX);
        self.0.read_range(&at, offset, len).map_err(|e| crate::anyhow!(e))
    }
}

impl g::GuestExtraction for Extraction {
    #[expect(clippy::unused_async_trait_impl, reason = "async in the contract, so the host can cancel a long call")]
    async fn begin(extractor: u32, declarations: &host::Declarations) -> Result<g::Extraction, String> {
        let extractor = registered().extractors.get(extractor as usize).ok_or("no such extractor")?;
        let session = (extractor.begin)(&Declarations(declarations)).map_err(|e| format!("{e:#}"))?;
        Ok(g::Extraction::new(Extraction(RefCell::new(session))))
    }

    #[expect(clippy::unused_async_trait_impl, reason = "async in the contract, so the host can cancel a long call")]
    async fn extract(&self, path: String, release: String, discs: &host::Discs) -> Result<Vec<(String, Vec<u8>)>, String> {
        self.0.borrow_mut().extract(&path, &release, &mut Discs(discs)).map_err(|e| format!("{e:#}"))
    }
}

/// An asset's view the host made without an asset.
struct Missing;

impl View for Missing {
    fn show(&mut self, ui: &mut crate::Ui) {
        ui.error("this view shows an asset, and none was given");
    }
}
