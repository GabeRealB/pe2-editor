/// The asset resource behind a lent asset: one the host passed, or one a query returned.
enum Held<'a> {
    Borrowed(&'a host::Asset),
    Owned(host::Asset),
}

/// An asset the host lent, read through its resource: its path and declaration once, its fields parsed when first
/// asked for.
struct Lent<'a> {
    handle: Held<'a>,
    path: String,
    uid: Option<String>,
    node_type: Option<String>,
    declaration: String,
    fields: OnceCell<Table>,
}

impl<'a> Lent<'a> {
    fn new(handle: Held<'a>) -> Lent<'a> {
        let resource = match &handle {
            Held::Borrowed(asset) => *asset,
            Held::Owned(asset) => asset,
        };
        let (path, uid, node_type) = (resource.path(), resource.uid(), resource.node_type());
        let declaration = resource.declaration();
        Lent { handle, path, uid, node_type, declaration, fields: OnceCell::new() }
    }

    fn borrowed(asset: &'a host::Asset) -> Lent<'a> {
        Lent::new(Held::Borrowed(asset))
    }

    fn resource(&self) -> &host::Asset {
        match &self.handle {
            Held::Borrowed(asset) => asset,
            Held::Owned(asset) => asset,
        }
    }

    fn asset(&self) -> Asset<'_> {
        Asset::new(self, self.node_type.as_deref())
    }
}

impl Source for Lent<'_> {
    fn path(&self) -> &str {
        &self.path
    }

    fn uid(&self) -> Option<&str> {
        self.uid.as_deref()
    }

    fn fields(&self) -> &Table {
        self.fields.get_or_init(|| toml::from_str(&self.declaration).unwrap_or_default())
    }

    fn declaration(&self) -> &str {
        &self.declaration
    }

    fn has_file(&self, name: &str) -> bool {
        self.resource().has_file(name)
    }

    fn read(&self, name: &str) -> crate::Result<Vec<u8>> {
        self.resource().read(name).map_err(crate::Error::msg)
    }

    fn size(&self, name: &str) -> Option<u64> {
        self.resource().size(name)
    }

    fn read_range(&self, name: &str, offset: u64, len: usize) -> crate::Result<Vec<u8>> {
        let len = u32::try_from(len).unwrap_or(u32::MAX);
        self.resource().read_range(name, offset, len).map_err(crate::Error::msg)
    }

    fn writer(&self, name: &str) -> Option<crate::Result<Box<dyn crate::FileWriter>>> {
        let writer = self.resource().writer(name).map_err(crate::Error::msg);
        Some(writer.map(|w| Box::new(HostWriter(Some(w))) as Box<dyn crate::FileWriter>))
    }

    fn temp(&self) -> Option<crate::Result<String>> {
        Some(self.resource().temp().map_err(crate::Error::msg))
    }

    fn entries(&self, folder: &str) -> Option<crate::Result<Vec<String>>> {
        Some(self.resource().entries(folder).map_err(crate::Error::msg))
    }

    fn read_entry(&self, path: &str) -> Option<crate::Result<Vec<u8>>> {
        Some(self.resource().read_entry(path).map_err(crate::Error::msg))
    }

    fn assets_of(&self, node_type: &str) -> Option<crate::Result<Vec<(String, String)>>> {
        Some(self.resource().assets_of(node_type).map_err(crate::Error::msg))
    }

    fn place(&self, path: &str) -> Option<String> {
        self.resource().place(path)
    }

    fn output_of(&self, path: &str, address: &str) -> Option<crate::Result<Data>> {
        Some(self.resource().output_of(path, address).map(from_wit).map_err(crate::Error::msg))
    }

    fn node_named(&self, reference: &str) -> Option<crate::NodeNamed> {
        self.resource().node_named(reference).map(|named| crate::NodeNamed {
            path: named.path,
            uid: named.uid,
            types: named.types,
        })
    }

    fn build_config(&self) -> Option<crate::data::BuildConfig> {
        self.resource().build_config().map(|c| crate::data::BuildConfig {
            name: c.name,
            release: c.release,
            target: c.target,
            folder: c.folder,
            known: c.known,
            properties: c.properties.parse().unwrap_or_default(),
        })
    }

    fn keep(&self, path: &str, name: &str) -> Option<crate::Result<crate::File>> {
        Some(self.resource().keep(path, name).map(file_from_wit).map_err(crate::Error::msg))
    }

    fn path_of(&self, name: &str) -> Option<String> {
        self.resource().path_of(name)
    }
}

/// A file being made through the host's writer: appended to there, finished into the file the host made.
struct HostWriter(Option<host::Writer>);

// SAFETY: a component runs on one thread.
unsafe impl Send for HostWriter {}

impl crate::FileWriter for HostWriter {
    fn append(&mut self, bytes: &[u8]) -> crate::Result<()> {
        let writer = self.0.as_ref().ok_or_else(|| crate::anyhow!("finished"))?;
        writer.append(bytes).map_err(crate::Error::msg)
    }

    fn finish(mut self: Box<Self>) -> crate::Result<crate::File> {
        let writer = self.0.take().ok_or_else(|| crate::anyhow!("finished"))?;
        writer.finish().map(file_from_wit).map_err(crate::Error::msg)
    }
}

/// The project the host lent, its answers kept for the call: an asset a query returns lives as long as the project.
struct Lens<'a> {
    project: &'a host::Project,
    #[expect(clippy::vec_box, reason = "a found asset stays where it is while more are found: assets borrow it")]
    found: RefCell<Vec<Box<Lent<'static>>>>,
}

impl<'a> Lens<'a> {
    fn new(project: &'a host::Project) -> Lens<'a> {
        Lens { project, found: RefCell::new(vec![]) }
    }

    fn keep(&self, asset: host::Asset) -> Asset<'_> {
        let lent = Box::new(Lent::new(Held::Owned(asset)));
        let at: *const Lent<'static> = &raw const *lent;
        self.found.borrow_mut().push(lent);
        // SAFETY: the box is kept, unmoved and unchanged, until the lens goes, and the asset borrows the lens.
        unsafe { &*at }.asset()
    }
}

impl Project for Lens<'_> {
    fn asset(&self, path: &str) -> Option<Asset<'_>> {
        self.project.asset(path).map(|a| self.keep(a))
    }

    fn resolve(&self, reference: &Value) -> Option<Asset<'_>> {
        self.project.resolve(&value_text(reference)).map(|a| self.keep(a))
    }

    fn find(&self, node_type: &str) -> Vec<Asset<'_>> {
        self.project.find(node_type).into_iter().map(|a| self.keep(a)).collect()
    }

    fn selection(&self) -> Option<Asset<'_>> {
        self.project.selection().map(|a| self.keep(a))
    }

    fn chosen(&self, path: &str, group: &str) -> Option<String> {
        self.project.chosen(path, group)
    }

    fn picture(&self, path: &str, look: Option<&str>) -> Option<crate::Result<Image>> {
        self.project.picture(path, look).map(|made| made.map(from_image).map_err(crate::Error::msg))
    }

    fn target(&self) -> Option<String> {
        self.project.target()
    }

    fn revision(&self) -> u64 {
        self.project.revision()
    }

    fn image(&self, path: &str, address: &str) -> Option<crate::Result<Image>> {
        self.project.image(path, address).map(|made| made.map(from_image).map_err(crate::Error::msg))
    }

    fn table(&self, path: &str, address: &str) -> Option<crate::Result<crate::Table>> {
        let told = self.project.table(path, address)?.map_err(crate::Error::msg);
        Some(told.and_then(|text| text.parse().map_err(|e| crate::anyhow!("{path}: {e}"))))
    }

    fn bytes(&self, path: &str, address: &str) -> Option<crate::Result<Vec<u8>>> {
        Some(self.project.bytes(path, address)?.map_err(crate::Error::msg))
    }

    fn request(&self, path: &str, address: &str) -> crate::Requested {
        match self.project.request(path, address) {
            host::Requested::Ready(bytes) => crate::Requested::Ready(bytes),
            host::Requested::Pending(waited) => crate::Requested::Pending { waited },
            host::Requested::Failed(why) => crate::Requested::Failed(why),
        }
    }

    fn call(&self, service: &str, arguments: &Value) -> crate::Result<Value> {
        let answer = self.project.call(service, &value_text(arguments)).map_err(crate::Error::msg)?;
        parse_value(&answer).ok_or_else(|| crate::anyhow!("{service}: its answer is not TOML"))
    }
}

fn from_image(image: types::Image) -> Image {
    Image { width: image.width as usize, height: image.height as usize, rgba: image.rgba }
}

/// A frame's `ui`: the one lent, or a row, a section or a body of it.
enum Handle<'a> {
    Lent(&'a host::Ui),
    Child(host::Ui),
}

struct Frame<'a> {
    ui: Handle<'a>,
    project: &'a Lens<'a>,
    asset: Option<Asset<'a>>,
}

impl Frame<'_> {
    fn ui(&self) -> &host::Ui {
        match &self.ui {
            Handle::Lent(ui) => ui,
            Handle::Child(ui) => ui,
        }
    }

    fn child(&self, ui: host::Ui) -> Box<dyn UiHost + '_> {
        Box::new(Frame { ui: Handle::Child(ui), project: self.project, asset: self.asset })
    }
}

fn style(style: Style) -> types::Style {
    match style {
        Style::Normal => types::Style::Normal,
        Style::Weak => types::Style::Weak,
        Style::Note => types::Style::Note,
        Style::Strong => types::Style::Strong,
        Style::Error => types::Style::Error,
    }
}

